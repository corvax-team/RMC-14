    [GenerateTypedNameReferences]
    public sealed partial class CharacterSetupGui : Control
    {
        [Dependency] private readonly IClientPreferencesManager _preferencesManager = default!;
        [Dependency] private readonly IEntityManager _entManager = default!;
        [Dependency] private readonly IPrototypeManager _protomanager = default!;
        [Dependency] private readonly IResourceCache _resourceCache = default!;

        private readonly HumanoidProfileEditor _profileEditor;
        private readonly List<(int Slot, ICharacterProfile Profile)> _carouselProfiles = new();
        private int _carouselIndex;
        private EntityUid _leftPreviewEntity;
        private EntityUid _centerPreviewEntity;
        private EntityUid _rightPreviewEntity;
        private EntityUid _leftFarPreviewEntity;
        private EntityUid _rightFarPreviewEntity;
        private string _centerPreviewSpeciesId = SharedHumanoidAppearanceSystem.DefaultSpecies;
        private bool _showClothes = true;
        private bool _deleteCounting;
        private bool _deleteReady;
        private float _deleteCountdown;
        private bool _dragging;
        private Vector2 _dragOffset;
        private Vector2 _manualPosition;
        private bool _hasManualPosition;
        private readonly Dictionary<SpriteView, float> _hoverRotationTimes = new();
        private readonly HashSet<SpriteView> _hoveredViews = new();
        private StyleNano.UiColorTheme _appliedTheme;
        private float _lastCarouselWidth = -1f;
        private CarouselLayoutMode _carouselLayoutMode = CarouselLayoutMode.Five;
