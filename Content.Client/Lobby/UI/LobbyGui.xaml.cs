        }

        private void OpenCrewManifest()
        {
            if (!TryGetLobbyStation(out var station))
                return;

            _entityManager.System<CrewManifestSystem>().RequestCrewManifest(station);
        }

        private bool TryGetLobbyStation(out NetEntity station)
        {
            var gameTicker = _entityManager.System<ClientGameTicker>();

            foreach (var entry in gameTicker.StationNames)
            {
                station = entry.Key;
                return true;
            }

            foreach (var entry in gameTicker.JobsAvailable)
            {
                station = entry.Key;
                return true;
            }

            station = default;
            return false;
        }

        private void ToggleReady(bool ready)
        {
            if (_suppressReadyToggle)
                return;

            UpdateReadyLabel(ready);
            _consoleHost.ExecuteCommand($"toggleready {ready.ToString().ToLowerInvariant()}");
        }
