        private static void SetThemeClass(Control control, bool crtEnabled)
        {
            if (crtEnabled)
            {
                control.AddStyleClass(StyleNano.StyleClassLobbyThemeCrt);
                control.RemoveStyleClass(StyleNano.StyleClassLobbyThemeClean);
            }
            else
            {
                control.AddStyleClass(StyleNano.StyleClassLobbyThemeClean);
                control.RemoveStyleClass(StyleNano.StyleClassLobbyThemeCrt);
            }
        }

        private static void ApplyGlow(Label label, bool crtEnabled)
        {
            if (crtEnabled)
            {
                label.FontColorShadowOverride = StyleNano.LobbyCrtGlow;
                label.ShadowOffsetXOverride = 1;
                label.ShadowOffsetYOverride = 1;
            }
            else
            {
                label.FontColorShadowOverride = null;
                label.ShadowOffsetXOverride = null;
                label.ShadowOffsetYOverride = null;
            }
        }

        private static void ApplyButtonGlow(Button button, bool crtEnabled)
        {
            ApplyGlow(button.Label, crtEnabled);
        }

        private void ToggleLeftMenu(bool show)
        {
            if (_leftMenuVisible == show)
                return;

            _leftMenuVisible = show;
            CenterMenuGlow.StopAnimation(LeftMenuHideAnimationKey);
            CenterMenuGlow.StopAnimation(LeftMenuShowAnimationKey);

            if (show)
            {
                LeftMenuToggleButton.Visible = false;
                CenterMenuGlow.Visible = true;
                CenterMenuGlow.Modulate = Color.Transparent;
                CenterMenuGlow.PlayAnimation(BuildLeftMenuAnimation(Color.Transparent, Color.White), LeftMenuShowAnimationKey);
            }
            else
            {
                CenterMenuGlow.PlayAnimation(BuildLeftMenuAnimation(Color.White, Color.Transparent), LeftMenuHideAnimationKey);
            }
        }

        private void OnLeftMenuAnimationCompleted(string key)
        {
            if (key == LeftMenuHideAnimationKey)
            {
                CenterMenuGlow.Visible = false;
                CenterMenuGlow.Modulate = Color.White;
                LeftMenuToggleButton.Visible = true;
            }
        }

        private static Animation BuildLeftMenuAnimation(Color from, Color to)
        {
            return new Animation
            {
                Length = TimeSpan.FromSeconds(0.15f),
                AnimationTracks =
                {
                    new AnimationTrackControlProperty
                    {
                        Property = nameof(Control.Modulate),
                        InterpolationMode = AnimationInterpolationMode.Linear,
                        KeyFrames =
                        {
                            new AnimationTrackProperty.KeyFrame(from, 0f),
                            new AnimationTrackProperty.KeyFrame(to, 0.15f)
                        }
                    }
                }
            };
        }

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);
            _leftMenuDragHelper.Update(args.DeltaSeconds);

            if (CenterMenuGlow.Visible)
                _leftMenuLastGlobal = CenterMenuGlow.GlobalPosition;

            // CCM rework lobby - start
            if (VoteContainer.Size.X > 1f && VoteContainer.Size.Y > 1f)
                _voteLastSize = VoteContainer.Size;
            // CCM rework lobby - end

            UpdateVoteContainerAnchor();
        }

        private void UpdateVoteContainerAnchor()
        {
            if (VoteContainer.Parent == null)
                return;

            // CCM rework lobby - start
            var voteSize = VoteContainer.Size;
            if (voteSize.X <= 1f || voteSize.Y <= 1f)
                voteSize = _voteLastSize;
            if (voteSize.X <= 1f || voteSize.Y <= 1f)
                return;

            var parentGlobal = VoteContainer.Parent.GlobalPosition;
            var menuSize = CenterMenuGlow.Size;
            if (menuSize.X <= 1f || menuSize.Y <= 1f)
                return;

            var menuGlobal = CenterMenuGlow.GlobalPosition;
            var voteX = menuGlobal.X + (menuSize.X - voteSize.X) * 0.5f - parentGlobal.X;
            var voteY = -parentGlobal.Y + 6f;
            // CCM rework lobby - end

            // CCM rework lobby - start
            var leftGlobal = LeftColumn.GlobalPosition;
            var leftSize = LeftColumn.Size;
            if (leftSize.X > 1f && leftSize.Y > 1f)
            {
                var minX = leftGlobal.X - parentGlobal.X;
                var maxX = minX + leftSize.X - voteSize.X;
                var minY = leftGlobal.Y - parentGlobal.Y;
                var maxY = minY + leftSize.Y - voteSize.Y;
                if (maxX >= minX)
                    voteX = Math.Clamp(voteX, minX, maxX);
                if (maxY >= minY)
                    voteY = Math.Clamp(voteY, minY, maxY);
            }

            LayoutContainer.SetAnchorPreset(VoteContainer, LayoutPreset.TopLeft);
            LayoutContainer.SetPosition(VoteContainer, new Vector2(voteX, voteY));
            // CCM rework lobby - end
        }

        private void OnLeftMenuDragKeyBindDown(GUIBoundKeyEventArgs args)
        {
            if (args.Function != EngineKeyFunctions.UIClick || !CenterMenuGlow.Visible)
                return;

            _leftMenuDragStarted = false;
            _leftMenuDragHelper.MouseDown(CenterMenuGlow);
            args.Handle();
        }

        private void OnLeftMenuDragKeyBindUp(GUIBoundKeyEventArgs args)
        {
            if (args.Function != EngineKeyFunctions.UIClick)
                return;

            _leftMenuDragHelper.EndDrag();
            args.Handle();
        }

        private bool OnBeginLeftMenuDrag()
        {
            if (!CenterMenuGlow.Visible || CenterMenuGlow.Parent == null)
                return false;

            _leftMenuDragStarted = true;

            if (!_leftMenuAnchorInitialized && CanInitializeLeftMenuAnchor())
                InitializeLeftMenuAnchor(CenterMenuGlow.GlobalPosition);

            var menuGlobal = CenterMenuGlow.GlobalPosition;

            _leftMenuDragOffset = UserInterfaceManager.MousePositionScaled.Position - menuGlobal;
            return true;
        }

        private bool OnContinueLeftMenuDrag(float frameTime)
        {
            if (!_leftMenuDragStarted || CenterMenuGlow.Parent == null)
                return false;

            var parentGlobal = CenterMenuGlow.Parent.GlobalPosition;
            var mousePos = UserInterfaceManager.MousePositionScaled.Position;
            var newPos = mousePos - _leftMenuDragOffset - parentGlobal;
            // CCM rework lobby - start
            var menuSize = CenterMenuGlow.Size;
            var leftGlobal = LeftColumn.GlobalPosition;
            var leftSize = LeftColumn.Size;
            if (leftSize.X > 1f && leftSize.Y > 1f && menuSize.X > 1f && menuSize.Y > 1f)
            {
                var minX = leftGlobal.X - parentGlobal.X;
                var maxX = minX + leftSize.X - menuSize.X;
                var minY = leftGlobal.Y - parentGlobal.Y;
                var maxY = minY + leftSize.Y - menuSize.Y;
                if (maxX >= minX)
                    newPos.X = Math.Clamp(newPos.X, minX, maxX);
                if (maxY >= minY)
                    newPos.Y = Math.Clamp(newPos.Y, minY, maxY);
            }
            // CCM rework lobby - end
            LayoutContainer.SetPosition(CenterMenuGlow, newPos);
            return true;
        }

        private void OnEndLeftMenuDrag()
        {
            _leftMenuDragStarted = false;
        }

        private void InitializeLeftMenuAnchor(Vector2 menuGlobal)
        {
            if (_leftMenuAnchorInitialized || CenterMenuGlow.Parent == null)
                return;

            var parentGlobal = CenterMenuGlow.Parent.GlobalPosition;
            LayoutContainer.SetAnchorPreset(CenterMenuGlow, LayoutPreset.TopLeft);
            LayoutContainer.SetPosition(CenterMenuGlow, menuGlobal - parentGlobal);
            _leftMenuAnchorInitialized = true;
        }

        private bool CanInitializeLeftMenuAnchor()
        {
            if (CenterMenuGlow.Parent == null)
                return false;

            var parentSize = CenterMenuGlow.Parent.Size;
            var menuSize = CenterMenuGlow.Size;
            return parentSize.X > 1f && parentSize.Y > 1f && menuSize.X > 1f && menuSize.Y > 1f;
        }


        private void UpdateReadyLabel(bool ready)
        {
            ReadyButton.Text = ready
                ? Loc.GetString("ui-lobby-ready-up-button")
                : Loc.GetString("ui-lobby-not-ready-button");
        }

        private void OpenTutorial()
        {
            if (_tutorialWindow == null || _tutorialWindow.Disposed)
            {
                _tutorialWindow = new RulesAndInfoWindow();
                _tutorialWindow.OnClose += () => _tutorialWindow = null;
            }

            _tutorialWindow.OpenCentered();
        }

        private void OpenStats()
        {
            if (_statsWindow == null || _statsWindow.Disposed)
            {
                _statsWindow = new RMCPlaytimeStatsWindow();
                _statsWindow.OnClose += () => _statsWindow = null;
            }

            _statsWindow.OpenCentered();
        }

        private void OpenCharacterSetup()
        {
            if (_stateManager.CurrentState is LobbyState lobby)
                lobby.SwitchState(LobbyGuiState.CharacterSetup);
        }

        private void OpenPolls()
        {
            if (_voteMenu == null || _voteMenu.Disposed)
            {
